"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const source=fs.readFileSync("js/rbac-role-experience.js","utf8");
const sandbox={window:{},document:{readyState:"loading",addEventListener(){}}};
vm.runInNewContext(source,sandbox);
const model=sandbox.window.ExamGuruRoleExperience;
assert.ok(model,"role experience model is exposed");
assert.deepEqual(Object.keys(model.roles).sort(),["institution_viewer","parent","platform_admin","school_admin","student","teacher"]);
assert.equal(model.roles.platform_admin.nav.some(x=>x[1]==="./admin.html"),true);
assert.equal(model.roles.school_admin.nav.some(x=>x[1]==="./institution-operations.html"),true);
assert.equal(model.roles.teacher.nav.some(x=>x[1]==="./assigned-test.html"),true);
assert.equal(model.roles.parent.nav.some(x=>x[1]==="./parent.html"),true);
assert.equal(model.roles.student.nav.some(x=>x[1]==="./dashboard.html"),true);
assert.equal(model.roles.institution_viewer.nav.length>0,true);
const platformRoles=model.capabilities.find(x=>x[0]==="Manage platform roles")[1];
assert.deepEqual(Array.from(platformRoles),["yes","no","no","no","no","no"]);
const learnerProgress=model.capabilities.find(x=>x[0]==="View learner progress")[1];
assert.equal(learnerProgress[4],"own");
assert.equal(learnerProgress[3],"scope");
const assessments=model.capabilities.find(x=>x[0]==="Create / assign assessments")[1];
assert.equal(assessments[3],"linked");
assert.equal(assessments[5],"no");
const exams=model.capabilities.find(x=>x[0]==="Take practice and examinations")[1];
assert.deepEqual(Array.from(exams),["no","no","no","no","own","no"]);
const assignmentManagement=model.capabilities.find(x=>x[0]==="Manage teacher assignments and enrolments")[1];
assert.equal(assignmentManagement[2],"no");
console.log("Role experience matrix model: all checks passed.");
