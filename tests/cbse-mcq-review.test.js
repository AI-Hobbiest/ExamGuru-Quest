"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs"),vm=require("node:vm");
const context={window:{},document:{getElementById:()=>null},String,Array,Object,Number,RegExp,Set,Map,JSON};
context.globalThis=context;vm.createContext(context);
vm.runInContext(fs.readFileSync("js/cbse-mcq-review.js","utf8"),context,{filename:"js/cbse-mcq-review.js"});
const review=context.window.C10CbseReview;
assert.ok(review,"CBSE review helpers are exposed for deterministic checks");
assert.equal(review.bankSubjectFor("mathematics-basic"),"mathematics");
assert.equal(review.bankSubjectFor("mathematics-standard"),"mathematics");
assert.equal(review.bankSubjectFor("hindi-a"),"hindi");
assert.equal(review.bankSubjectFor("science"),"science");
assert.equal(review.sourceBadge({type:"CBSE_PYQ",year:"2023"}),"CBSE-2023 Question");
assert.equal(review.sourceBadge({type:"CBSE_PYQ",year:"bad"}),"");
assert.equal(review.sourceBadge({type:"SOF",year:"2023"}),"");
assert.equal(review.safeOfficialPackageUrl("https://www.cbse.gov.in/cbsenew/question-paper/2026/X/Science.zip"),true);
assert.equal(review.safeOfficialPackageUrl("https://example.com/paper.zip"),false);
assert.ok(fs.readFileSync("js/cbse-mcq-review.js","utf8").includes("Open official CBSE marking-scheme ZIP"),"review panel links to the official marking-scheme archive");
assert.ok(!fs.readFileSync("js/cbse-mcq-review.js","utf8").includes("cbse-papers/files/"),"educator review must not depend on mirrored PDFs");
const a=review.candidateFingerprint("Which gas is released? ",["Nitrogen","Oxygen","Hydrogen","Methane"]);
const b=review.candidateFingerprint("which gas is released",["Methane","Hydrogen","Oxygen","Nitrogen"]);
assert.equal(a,b,"duplicate matching ignores case, whitespace and option order");
const admin=fs.readFileSync("js/admin-manager.js","utf8");
assert.ok(admin.includes("approveCbseCandidate")&&admin.includes("CBSE_PYQ")&&admin.includes("already exists"),"Admin promotion validates provenance and blocks duplicate question content");
const page=fs.readFileSync("admin.html","utf8");
assert.ok(page.includes('data-tab="cbse-review"')&&page.includes('id="cbseReviewConfirm"')&&page.includes('id="cbseReviewCorrectOption"'),"Admin review UI requires manual answer/source confirmation");
const quiz=fs.readFileSync("js/quiz-engine.js","utf8");
assert.ok(quiz.includes("sourceBadgeFor")&&quiz.includes("CBSE-"),"student quiz renderer exposes year-specific CBSE provenance");
console.log("CBSE review tests passed: subject mapping, source badge, content deduplication, official source links, mandatory educator confirmation and provenance-preserving promotion.");
